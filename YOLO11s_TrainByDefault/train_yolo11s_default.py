#!/usr/bin/env python3
"""Train yolo11s on the BDD100K 5-class vehicle dataset with 100% DEFAULT
Ultralytics hyperparameters (epochs, batch, imgsz, lr, augmentation, etc -
nothing overridden). This is the baseline training run to compare against
DANN later.

Self-contained: lives in YOLO11s_TrainByDefault/ alongside its own results.
Uses data_bdd100k_vehicle5_local.yaml (built by prepare_train_yaml.py) which
points to absolute image paths - run that script first. All training
outputs (weights, logs, plots) are written under THIS folder.

Usage (run from inside YOLO11s_TrainByDefault/, AFTER prepare_train_yaml.py):
  python prepare_train_yaml.py
  python train_yolo11s_default.py
"""
from pathlib import Path

from ultralytics import YOLO

HERE = Path(__file__).resolve().parent  # YOLO11s_TrainByDefault/
DATA_YAML = HERE / "data_bdd100k_vehicle5_local.yaml"  # generated by prepare_train_yaml.py


def main():
    if not DATA_YAML.exists():
        raise SystemExit(
            f"FLAG: {DATA_YAML} not found - run prepare_train_yaml.py first "
            "(it builds the absolute-path data.yaml this script needs)"
        )

    model = YOLO("yolo11s.pt")  # pretrained COCO weights, auto-downloads if not present locally

    # NOTHING below is overridden except where results are saved (project/name).
    # Every other value (epochs, batch, imgsz, lr0, optimizer, augmentation...)
    # is whatever Ultralytics ships as its own default.
    model.train(
        data=str(DATA_YAML),
        project=str(HERE),
        name="run1",
    )


if __name__ == "__main__":
    main()