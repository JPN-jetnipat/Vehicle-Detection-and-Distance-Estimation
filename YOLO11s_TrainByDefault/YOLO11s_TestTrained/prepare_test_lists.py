#!/usr/bin/env python3
"""Build absolute-path image lists + a data.yaml for evaluating the TRAINED
model (best.pt from YOLO11s_TrainByDefault/run1/weights/best.pt) - no COCO
class-id remap needed here, since the trained model predicts using our own
5-class ids directly (car=0, truck=1, bus=2, motor=3, bike=4), same as
dataset/yolo/labels/ already uses.

Reads from the main bdd100k_split_handoff repo (read-only, untouched):
  - splits/val.txt, splits/test.txt          (bare filenames)
  - dataset/yolo/attr_index.json             (timeofday per image)
  - dataset/yolo/images|labels/train/        (project's own val lives here)
  - dataset/yolo/images|labels/val/          (TEST = BDD official val)

Writes into THIS folder (YOLO11s_TestTrained/):
  - splits_local/{val,test_all,test_day,test_night,test_dawndusk}_images.txt
  - data_bdd100k_vehicle5_local.yaml

Usage (run from inside YOLO11s_TestTrained/):
  python prepare_test_lists.py
"""
import json
from collections import defaultdict
from pathlib import Path

# ---- EDIT THIS if your bdd100k_split_handoff folder is somewhere else ----
REPO_ROOT = Path(r"C:\Users\USER\OneDrive\เดสก์ท็อป\baby\bdd100k_split_handoff")
# ---------------------------------------------------------------------------

HERE = Path(__file__).resolve().parent
YOLO = REPO_ROOT / "dataset" / "yolo"
SPLITS_SRC = REPO_ROOT / "splits"
SPLITS_OUT = HERE / "splits_local"
YAML_OUT = HERE / "data_bdd100k_vehicle5_local.yaml"

NAMES = {0: "car", 1: "truck", 2: "bus", 3: "motor", 4: "bike"}
TIMEOFDAY_TO_STRATUM = {"daytime": "day", "night": "night", "dawn/dusk": "dawndusk"}


def build_list(names, img_dir: Path, out_stem: str) -> Path:
    written, missing = [], 0
    for name in names:
        img = img_dir / name
        if img.exists():
            written.append(str(img.resolve()))
        else:
            missing += 1
    out_path = SPLITS_OUT / f"{out_stem}_images.txt"
    out_path.write_text("\n".join(written) + "\n", encoding="utf-8")
    if missing:
        print(f"  WARNING: {missing} names for {out_stem} had no matching image, skipped")
    print(f"{out_stem}: {len(written)} images -> {out_path}")
    return out_path


def main():
    if not YOLO.exists():
        raise SystemExit(f"FLAG: {YOLO} not found - check REPO_ROOT at the top of this script")

    SPLITS_OUT.mkdir(parents=True, exist_ok=True)
    attr = json.loads((YOLO / "attr_index.json").read_text(encoding="utf-8"))

    # 1) project's own VAL (dev set, lives under images/train)
    val_names = [l.strip() for l in (SPLITS_SRC / "val.txt").read_text(encoding="utf-8").splitlines() if l.strip()]
    build_list(val_names, YOLO / "images" / "train", "eval_val")

    # 2) TEST, overall + split by timeofday (lives under images/val = BDD official val)
    test_names = [l.strip() for l in (SPLITS_SRC / "test.txt").read_text(encoding="utf-8").splitlines() if l.strip()]
    build_list(test_names, YOLO / "images" / "val", "eval_test_all")

    buckets = defaultdict(list)
    n_missing_attr = 0
    for name in test_names:
        a = attr.get(name)
        if a is None:
            n_missing_attr += 1
            continue
        stratum = TIMEOFDAY_TO_STRATUM.get(a["timeofday"])
        if stratum is None:
            continue
        buckets[stratum].append(name)
    if n_missing_attr:
        print(f"WARNING: {n_missing_attr} test names not found in attr_index.json")

    for stratum, names in buckets.items():
        build_list(names, YOLO / "images" / "val", f"eval_test_{stratum}")

    # data.yaml - path: . plus absolute train/val overridden per-run by eval script,
    # so the placeholder values here just need to exist and be valid.
    yaml_text = (
        "# Auto-generated by prepare_test_lists.py - placeholder train/val,\n"
        "# eval_trained_model.py overrides 'val' per run.\n"
        "path: .\n"
        f"train: {SPLITS_OUT.resolve() / 'eval_val_images.txt'}\n"
        f"val: {SPLITS_OUT.resolve() / 'eval_val_images.txt'}\n\n"
        "names:\n" + "\n".join(f"  {k}: {v}" for k, v in NAMES.items()) + "\n"
    )
    YAML_OUT.write_text(yaml_text, encoding="utf-8")
    print(f"\nWrote {YAML_OUT}")
    print("Next (after training finishes): python eval_trained_model.py")


if __name__ == "__main__":
    main()
