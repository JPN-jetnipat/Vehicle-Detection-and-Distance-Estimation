#!/usr/bin/env python3
"""Build a self-contained training data.yaml with ABSOLUTE image-path lists,
so `yolo detect train` doesn't get confused by Ultralytics' global
datasets_dir setting or by splits/*.txt only containing bare filenames.

Reads from the main bdd100k_split_handoff repo (read-only, untouched):
  - splits/train_100.txt, splits/val.txt   (bare filenames)
  - dataset/yolo/images/train/<name>.jpg   (both train_100 and val images
    live here - val is a 2.5% carve-out FROM the train pool, materialized
    into the same folder)
  - dataset/yolo/labels/train/<name>.txt   (already 0-4 class ids, no remap needed)

Writes into THIS folder (YOLO11s_TrainByDefault/):
  - splits_local/train_100_images.txt   (absolute paths)
  - splits_local/val_images.txt         (absolute paths)
  - data_bdd100k_vehicle5_local.yaml    (training data config)

Usage (run from inside YOLO11s_TrainByDefault/):
  python prepare_train_yaml.py
"""
from pathlib import Path

# ---- EDIT THIS if your bdd100k_split_handoff folder is somewhere else ----
REPO_ROOT = Path(r"C:\Users\USER\OneDrive\เดสก์ท็อป\baby\bdd100k_split_handoff")
# ---------------------------------------------------------------------------

HERE = Path(__file__).resolve().parent
SPLITS_SRC = REPO_ROOT / "splits"
IMG_TRAIN_DIR = REPO_ROOT / "dataset" / "yolo" / "images" / "train"
SPLITS_OUT = HERE / "splits_local"
YAML_OUT = HERE / "data_bdd100k_vehicle5_local.yaml"

NAMES = {0: "car", 1: "truck", 2: "bus", 3: "motor", 4: "bike"}


def build_list(names_file: str, out_stem: str) -> Path:
    names = [l.strip() for l in (SPLITS_SRC / names_file).read_text(encoding="utf-8").splitlines() if l.strip()]
    out_path = SPLITS_OUT / f"{out_stem}_images.txt"
    written, missing = [], 0
    for name in names:
        img = IMG_TRAIN_DIR / name
        if img.exists():
            written.append(str(img.resolve()))
        else:
            missing += 1
    out_path.write_text("\n".join(written) + "\n", encoding="utf-8")
    if missing:
        print(f"  WARNING: {missing} names in {names_file} had no matching image, skipped")
    print(f"{out_stem}: {len(written)} images -> {out_path}")
    return out_path


def main():
    if not IMG_TRAIN_DIR.exists():
        raise SystemExit(f"FLAG: {IMG_TRAIN_DIR} not found - check REPO_ROOT at the top of this script")

    SPLITS_OUT.mkdir(parents=True, exist_ok=True)

    train_list = build_list("train_100.txt", "train_100")
    val_list = build_list("val.txt", "val")

    yaml_text = (
        "# Auto-generated by prepare_train_yaml.py - absolute paths, avoids\n"
        "# Ultralytics' global datasets_dir path-join bug with the original\n"
        "# configs/data/bdd100k_vehicle5.yaml. Do not edit train:/val: by hand,\n"
        "# regenerate instead if the source splits change.\n"
        "path: .\n"
        f"train: {train_list.resolve()}\n"
        f"val: {val_list.resolve()}\n\n"
        "names:\n" + "\n".join(f"  {k}: {v}" for k, v in NAMES.items()) + "\n"
    )
    YAML_OUT.write_text(yaml_text, encoding="utf-8")
    print(f"\nWrote {YAML_OUT}")
    print("Next: python train_yolo11s_default.py")


if __name__ == "__main__":
    main()
