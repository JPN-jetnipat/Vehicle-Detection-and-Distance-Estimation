#!/usr/bin/env python3
"""Build a DAYTIME-ONLY training data.yaml with absolute image paths.

Same logic as YOLO11s_TrainByDefault/prepare_train_yaml.py, plus one filter:
keep only images whose BDD100K attribute timeofday == "daytime".

Reads (read-only):
  - REPO_ROOT/splits/train_100.txt, splits/val.txt   (bare filenames)
  - REPO_ROOT/dataset/yolo/images/train/<name>.jpg
  - BDD100K original label JSONs (for attributes.timeofday)

Writes into THIS folder (YOLOv5s_DayOnly_Set3/):
  - splits_local/train_day_images.txt
  - splits_local/val_day_images.txt
  - data_bdd100k_vehicle5_day.yaml

Usage (run from inside YOLOv5s_DayOnly_Set3/):
  python prepare_train_yaml_day.py
"""
import json
from pathlib import Path

# ---- EDIT THESE if your folders are somewhere else ----
REPO_ROOT = Path(r"C:\Users\USER\OneDrive\เดสก์ท็อป\baby\bdd100k_split_handoff")
BDD_LABELS_DIR = Path(r"C:\Users\USER\OneDrive\เดสก์ท็อป\baby\bdd100k\bdd100k_labels_release")
# --------------------------------------------------------

HERE = Path(__file__).resolve().parent
SPLITS_SRC = REPO_ROOT / "splits"
IMG_TRAIN_DIR = REPO_ROOT / "dataset" / "yolo" / "images" / "train"
SPLITS_OUT = HERE / "splits_local"
YAML_OUT = HERE / "data_bdd100k_vehicle5_day.yaml"

NAMES = {0: "car", 1: "truck", 2: "bus", 3: "motor", 4: "bike"}  # same order as YOLO11 run
EXPECTED_DAY_TOTAL = 29699  # proposal Table 1 (train + val, daytime)


def load_timeofday() -> dict:
    """Map image filename -> timeofday from the original BDD100K label JSONs."""
    tod = {}
    for fname in ("bdd100k_labels_images_train.json", "bdd100k_labels_images_val.json"):
        hits = list(BDD_LABELS_DIR.rglob(fname))
        if not hits:
            raise SystemExit(f"FLAG: {fname} not found under {BDD_LABELS_DIR}")
        print(f"Loading {hits[0]} ...")
        for item in json.loads(hits[0].read_text(encoding="utf-8")):
            tod[item["name"]] = item["attributes"]["timeofday"]
    print(f"timeofday entries: {len(tod)}")
    return tod


def build_list(names_file: str, out_stem: str, tod: dict) -> tuple[Path, int]:
    names = [l.strip() for l in (SPLITS_SRC / names_file).read_text(encoding="utf-8").splitlines() if l.strip()]
    out_path = SPLITS_OUT / f"{out_stem}_images.txt"
    written, missing_img, missing_attr = [], 0, 0
    for name in names:
        if name not in tod:
            missing_attr += 1
            continue
        if tod[name] != "daytime":
            continue
        img = IMG_TRAIN_DIR / name
        if img.exists():
            written.append(str(img.resolve()))
        else:
            missing_img += 1
    out_path.write_text("\n".join(written) + "\n", encoding="utf-8")
    if missing_img:
        print(f"  WARNING: {missing_img} daytime names in {names_file} had no image, skipped")
    if missing_attr:
        print(f"  WARNING: {missing_attr} names in {names_file} had no timeofday attribute, skipped")
    print(f"{out_stem}: {len(names)} listed -> {len(written)} daytime images -> {out_path}")
    return out_path, len(written)


def main():
    if not IMG_TRAIN_DIR.exists():
        raise SystemExit(f"FLAG: {IMG_TRAIN_DIR} not found - check REPO_ROOT")

    SPLITS_OUT.mkdir(parents=True, exist_ok=True)
    tod = load_timeofday()

    train_list, n_train = build_list("train_100.txt", "train_day", tod)
    # Val is also day-only: checkpoint selection must not see night data.
    val_list, n_val = build_list("val.txt", "val_day", tod)

    print(f"\nTotal daytime (train + val): {n_train + n_val}  | expected: {EXPECTED_DAY_TOTAL}")

    yaml_text = (
        "# Auto-generated by prepare_train_yaml_day.py - DAYTIME ONLY, absolute paths.\n"
        "path: .\n"
        f"train: {train_list.resolve()}\n"
        f"val: {val_list.resolve()}\n\n"
        "names:\n" + "\n".join(f"  {k}: {v}" for k, v in NAMES.items()) + "\n"
    )
    YAML_OUT.write_text(yaml_text, encoding="utf-8")
    print(f"Wrote {YAML_OUT}")
    print("Next: python train_yolov5s_day_set3.py")


if __name__ == "__main__":
    main()
